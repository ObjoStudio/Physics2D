"""Generate docs/API.md from the verified declarations in dist/Physics2D.objobasic.

The distribution file is the single shipped source of the module's public
declarations, and every member carries the `##` documentation comment the
compiler enforces. This generator assembles those verified declarations into
the reference document; prose lives in the curated category map below so a
regeneration keeps the narrative while refreshing every declaration.

Usage: python3 tools/generate_api_docs.py
Exits non-zero when a curated class is missing from the dist (which means the
document would publish aspirational or stale names).
"""

